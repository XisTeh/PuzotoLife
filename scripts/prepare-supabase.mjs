import fs from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';

// Gera somente estrutura. Nenhum valor do banco é incluído no arquivo SQL.
const source = path.resolve(process.argv[2] || 'Info/puzoto_life-consistente.db');
const db = new Database(source, { readonly: true });
const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
const identifier = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/i.test(name)) throw new Error('Identificador inesperado no schema.');
  return `"${name}"`;
};
const sql = [
  '-- Estrutura importada do SQLite; sem dados pessoais. Revisar antes de aplicar.',
  '-- O runtime ainda precisa ser portado: este schema não altera o banco utilizado pela aplicação.',
  'BEGIN;',
  'CREATE SCHEMA IF NOT EXISTS puzoto;',
  'REVOKE ALL ON SCHEMA puzoto FROM PUBLIC, anon, authenticated;',
  'SET LOCAL search_path = puzoto, public;',
];
const relations = [];
for (const table of tables) {
  const columns = db.prepare(`PRAGMA table_info(${identifier(table.name)})`).all();
  const definitions = columns.map((column) => {
    const type = column.type.toUpperCase();
    let definition = `${identifier(column.name)} ${type === 'INTEGER' ? 'BIGINT' : type === 'REAL' ? 'DOUBLE PRECISION' : type === 'BLOB' ? 'BYTEA' : 'TEXT'}`;
    if (column.pk) definition += type === 'INTEGER' ? ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : ' PRIMARY KEY';
    if (column.notnull && !column.pk) definition += ' NOT NULL';
    if (column.dflt_value != null && !column.pk) {
      let value = column.dflt_value;
      if (/datetime\(/i.test(value)) value = "to_char(timezone('America/Sao_Paulo', now()), 'YYYY-MM-DD HH24:MI:SS')";
      if (/strftime|julianday/i.test(value)) throw new Error(`Default não suportado: ${table.name}.${column.name}`);
      definition += ` DEFAULT ${value}`;
    }
    return definition;
  });
  // Preservar checks de domínio simples, sem interpretar valores de dados.
  for (const match of table.sql.matchAll(/CHECK\s*\(((?:[^()]|\([^()]*\))*)\)/gi)) definitions.push(`CHECK (${match[1]})`);
  for (const index of db.prepare(`PRAGMA index_list(${identifier(table.name)})`).all().filter((item) => item.unique && item.origin !== 'pk')) {
    const names = db.prepare(`PRAGMA index_info(${identifier(index.name)})`).all().map((item) => identifier(item.name));
    definitions.push(`UNIQUE (${names.join(', ')})`);
  }
  sql.push(`CREATE TABLE ${identifier(table.name)} (\n  ${definitions.join(',\n  ')}\n);`);
  sql.push(`ALTER TABLE ${identifier(table.name)} ENABLE ROW LEVEL SECURITY;`);
  sql.push(`ALTER TABLE ${identifier(table.name)} FORCE ROW LEVEL SECURITY;`);
  sql.push(`REVOKE ALL ON ${identifier(table.name)} FROM PUBLIC, anon, authenticated;`);
  // Sem policies de cliente: deny by default. Acesso do runtime será via papel dedicado.
  for (const fk of db.prepare(`PRAGMA foreign_key_list(${identifier(table.name)})`).all()) {
    relations.push(`ALTER TABLE ${identifier(table.name)} ADD FOREIGN KEY (${identifier(fk.from)}) REFERENCES ${identifier(fk.table)} (${identifier(fk.to)}) ON DELETE ${fk.on_delete} ON UPDATE ${fk.on_update} DEFERRABLE INITIALLY DEFERRED;`);
  }
}
sql.push(...relations);
for (const index of db.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all()) sql.push(`${index.sql};`);
sql.push('COMMIT;', '');
fs.mkdirSync('supabase/migrations', { recursive: true });
fs.writeFileSync('supabase/migrations/202609040001_legacy_structure.sql', sql.join('\n'));
fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/schema-manifest.json', `${JSON.stringify({ source: 'SQLite schema only', tables: tables.map((table) => ({ name: table.name, columns: db.prepare(`PRAGMA table_info(${identifier(table.name)})`).all().map((column) => ({ name: column.name, type: column.type, primaryKey: Boolean(column.pk) })) })) }, null, 2)}\n`);
db.close();
console.log(`Estrutura preparada: ${tables.length} tabelas. Nenhum registro exportado para o código.`);
